#!/usr/bin/env node
/**
 * Build the GitHub Action's verifier: action/dist/gleipnir-verify.mjs, the TypeScript CLI
 * (packages/verify/src/cli.ts) bundled with its dependencies into one dependency-free Node file,
 * so the action runs without `npm ci`. Not minified, so it can be reviewed.
 *
 * Usage (in typescript/): npm run build:action  (a test fails if the file is stale)
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = join(HERE, "../../action/dist/gleipnir-verify.mjs");

export async function buildAction() {
  const result = await build({
    entryPoints: [join(HERE, "../packages/verify/src/cli.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    minify: false,
    legalComments: "inline",
    write: false,
    logLevel: "warning",
    banner: { js: "// Generated by typescript/scripts/build-action.mjs from packages/verify/src. Do not edit." },
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = await buildAction();
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, out);
  console.log(`wrote action/dist/gleipnir-verify.mjs (${(out.length / 1024).toFixed(0)} KiB)`);
}
