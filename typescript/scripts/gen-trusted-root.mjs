#!/usr/bin/env node
/**
 * Regenerate packages/verify/src/data/trusted-root.ts from the Python verifier's pinned
 * Sigstore trusted root (python/gleipnir-verify/src/gleipnir_verify/data/sigstore_trusted_root.json).
 * A test fails if the two diverge.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const TS = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(TS, "../python/gleipnir-verify/src/gleipnir_verify/data/sigstore_trusted_root.json");
const root = JSON.parse(readFileSync(src, "utf8"));
const out = join(TS, "packages/verify/src/data/trusted-root.ts");
writeFileSync(
  out,
  `/* Generated by scripts/gen-trusted-root.mjs from the Python verifier's sigstore_trusted_root.json. Do not edit. */\n` +
    `export const TRUSTED_ROOT: unknown = ${JSON.stringify(root, null, 2)};\n`,
);
console.log("wrote", out);
